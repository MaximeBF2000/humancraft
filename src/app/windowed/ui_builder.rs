use super::render_types::Vertex;
use super::ui::UiRect;

#[derive(Default)]
pub(super) struct UiMeshBuilder {
    vertices: Vec<Vertex>,
    indices: Vec<u32>,
}

impl UiMeshBuilder {
    pub(super) fn finish(self) -> (Vec<Vertex>, Vec<u32>) {
        (self.vertices, self.indices)
    }

    pub(super) fn button(&mut self, rect: UiRect, label: &str, disabled: bool) {
        self.rect(
            rect,
            if disabled {
                [0.16, 0.16, 0.16]
            } else {
                [0.24, 0.24, 0.24]
            },
        );
        self.rect(
            UiRect::new(
                rect.left + 0.008,
                rect.bottom + 0.008,
                rect.right - 0.008,
                rect.top - 0.008,
            ),
            if disabled {
                [0.24, 0.24, 0.24]
            } else {
                [0.42, 0.42, 0.40]
            },
        );
        if !disabled {
            self.rect(
                UiRect::new(
                    rect.left + 0.014,
                    rect.top - 0.022,
                    rect.right - 0.014,
                    rect.top - 0.012,
                ),
                [0.64, 0.64, 0.60],
            );
            self.rect(
                UiRect::new(
                    rect.left + 0.014,
                    rect.bottom + 0.012,
                    rect.right - 0.014,
                    rect.bottom + 0.022,
                ),
                [0.29, 0.29, 0.28],
            );
        }
        let scale = button_label_scale(label, rect);
        self.center_text(
            rect.center_x(),
            rect.center_y() + 3.5 * scale,
            scale,
            if disabled {
                [0.50, 0.50, 0.50]
            } else {
                [0.95, 0.95, 0.92]
            },
            label,
        );
    }

    pub(super) fn field(&mut self, rect: UiRect, value: &str, focused: bool) {
        self.rect(
            rect,
            if focused {
                [0.48, 0.48, 0.42]
            } else {
                [0.24, 0.25, 0.25]
            },
        );
        self.rect(
            UiRect::new(
                rect.left + 0.006,
                rect.bottom + 0.006,
                rect.right - 0.006,
                rect.top - 0.006,
            ),
            [0.12, 0.13, 0.13],
        );
        self.text(
            rect.left + 0.025,
            rect.bottom + 0.040,
            0.0058,
            [0.94, 0.94, 0.90],
            value,
        );
    }

    pub(super) fn rect(&mut self, rect: UiRect, color: [f32; 3]) {
        self.quad(
            [
                [rect.left, rect.bottom, 0.0],
                [rect.right, rect.bottom, 0.0],
                [rect.right, rect.top, 0.0],
                [rect.left, rect.top, 0.0],
            ],
            color,
        );
    }

    pub(super) fn quad(&mut self, positions: [[f32; 3]; 4], color: [f32; 3]) {
        let base = self.vertices.len() as u32;
        for position in positions {
            self.vertices.push(Vertex {
                position,
                color,
                tex_coords: [0.0, 0.0],
            });
        }
        self.indices
            .extend_from_slice(&[base, base + 1, base + 2, base, base + 2, base + 3]);
    }

    pub(super) fn center_text(
        &mut self,
        center_x: f32,
        y: f32,
        scale: f32,
        color: [f32; 3],
        text: &str,
    ) {
        let width = text.chars().count() as f32 * 6.0 * scale;
        self.text(center_x - width * 0.5, y, scale, color, text);
    }

    pub(super) fn text(&mut self, x: f32, y: f32, scale: f32, color: [f32; 3], text: &str) {
        let mut cursor_x = x;
        for character in text.chars() {
            self.glyph(cursor_x, y, scale, color, character);
            cursor_x += 6.0 * scale;
        }
    }

    fn glyph(&mut self, x: f32, y: f32, scale: f32, color: [f32; 3], character: char) {
        let glyph = glyph_rows(character);
        for (row, bits) in glyph.iter().enumerate() {
            for (column, bit) in bits.chars().enumerate() {
                if bit == '1' {
                    let left = x + column as f32 * scale;
                    let top = y - row as f32 * scale;
                    self.rect(UiRect::new(left, top - scale, left + scale, top), color);
                }
            }
        }
    }
}

fn button_label_scale(label: &str, rect: UiRect) -> f32 {
    let max_width = (rect.right - rect.left - 0.06).max(0.08);
    let base = 0.0054;
    let text_width = label.chars().count() as f32 * 6.0 * base;
    if text_width <= max_width {
        base
    } else {
        (max_width / (label.chars().count() as f32 * 6.0)).max(0.0038)
    }
}

